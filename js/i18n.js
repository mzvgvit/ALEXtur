  const KEY = 'alextur-lang';
  let lang = 'ru';
  try { const s = localStorage.getItem(KEY); if (s && DICT[s]) lang = s; } catch (e) { /* приватный режим */ }

  function t(k) { return (DICT[lang] && DICT[lang][k]) || DICT.ru[k] || ''; }
  function pick(o) { if (!o || typeof o !== 'object') return o; return o[lang] || o.ru || ''; }

  // Картинки: alt + data-fallback сразу в нужном языке — fallback-заглушка
  // в main.js получит уже переведённый текст.
  function putText(el, val) { if (el.tagName === 'IMG') { el.alt = val; el.dataset.fallback = val; } else el.textContent = val; }

  function applyAll() {
    document.documentElement.lang = lang;
    const page = document.body.dataset.page;
    if (page) {
      document.title = t(page + '.title');
      const m = document.querySelector('meta[name="description"]');
      if (m) m.setAttribute('content', t(page + '.desc'));
    }
    document.querySelectorAll('[data-i18n]').forEach(el => putText(el, t(el.dataset.i18n)));
    document.querySelectorAll('[data-i18n-attr]').forEach(el => {
      el.dataset.i18nAttr.split(';').forEach(pair => {
        const [a, k] = pair.split(':');
        if (a && k) el.setAttribute(a.trim(), t(k.trim()));
      });
    });
  }

  const I18N = {
    lang: () => lang,
    t: t, pick: pick,
    set(l) {
      if (!DICT[l]) return;
      lang = l;
      try { localStorage.setItem(KEY, l); } catch (e) { /* приватный режим */ }
      applyAll();
      window.dispatchEvent(new CustomEvent('alextur:lang'));
    }
  };
  window.I18N = I18N;

  document.addEventListener('DOMContentLoaded', applyAll);
  window.addEventListener('alextur:lang', applyAll);
